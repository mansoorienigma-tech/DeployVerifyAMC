%% Deploy and Verify Modulation Classification on RFSoC Devices 
% This example shows how to deploy a pretrained convolutional neural
% network (CNN) for modulation classification to the AMD(R) Zynq(R)
% UltraScale+&trade; RFSoC devices. The pretrained network is trained by
% using generated synthetic and channel-impaired waveforms. 
% 
% Copyright 2025 The MathWorks, Inc.


%% Introduction
%
% The modulation classification application consists of two main modules: a
% preprocessing module and a neural network module. The preprocessing
% module formats the input signal from the RF Data Converter block and
% feeds the data to the NN block for classification. The neural network
% module consists of multiple fully connected layers and convolutional
% layers. These layers perform feature extraction and effective modulation
% classification of the modulated input signals. This example is based on
% the <docid:dlhdl_ug#mw_eec4af0e-acf3-4bc8-bb92-b2648ef9b7b0 Modulation
% Classification by Using FPGA> example in MATLAB(R).

%% Supported Hardware Platforms
% 
% AMD Zynq UltraScale+ RFSoC ZCU111 Evaluation Kit + XM500 balun card 
% 

