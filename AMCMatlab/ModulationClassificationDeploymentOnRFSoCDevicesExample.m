%% Model Device Under Test
%
% This section describes the design of the modulation classification
% system. The design is based on the |Deep Learning design with I/Q DAC/ADC
% and real-time interfaces| reference design in SoC Blockset(TM). The
% reference design supports the AXI4-Stream to hardware, hardware to
% AXI4-Stream, AXI4 Master DDR, RF data converter, and deep learning HDL
% interfaces. The reference design also supports up to 128-bit wide
% AXI4-Stream and AXI4 Master interfaces to operate at higher sampling
% rates of the RF data converter. To learn more about the reference design,
% see <docid:soc_ug#mw_02569ac6-46ba-48d0-963a-79058ea85571 Reference
% Designs for RFSoC Devices>.
% 
% <<../rfsocmodClassDUTRAM.png>>
%

%%
% The reference design contains a |Transmit Repeat| DUT and a |Capture|
% DUT. In the |Transmit Repeat| DUT, there is a provision to transmit a
% test tone or a waveform loaded onto LUT-based RAMs. There are multiple
% RAMs to accommodate multiple test waveforms of interest. There is also a
% provision to select the Tx source either from the LUT-based RAMs or the
% tone generated by the NCO.
% 
% In the |Capture| DUT, there is a provision for triggering and capturing a
% frame of samples from MATLAB. This is achieved through ADI AXI DMA
% controller, which is used to move the data from the FPGA fabric to the
% processor in the reference design. The data is sent from the trigger
% capture subsystem, through the DMA controller and AXI4-Stream interface,
% to the MATLAB host. This setup is used for capturing real-world
% samples for offline training.
% 
% The DUT contains two AXI4 Master interfaces. One AXI4 interface is
% connected to the deep learning processor IP core, and the other is
% connected to the DDR memory interface generator (MIG) IP.
%
% <<../rfsocmodClassDUT.png>>
%
% Start the targeting workflow by opening the
% |soc_dlmc_rfsoc_zcu111.slx| model. Right-click the |Modulation
% Classification DUT| and select *HDL Code* > *HDL Workflow Advisor*.
% 
% 1. In step 1.1, set *Target workflow* to |IP Core Generation| and *Target
% platform* to |Xilinx Zynq UltraScale+ RFSoC ZCU111 Evaluation Kit|.
%
% <<../IPCoreGenWorkflow1.png>>
%
% 2. In step 1.2, set *Reference design* to |Deep Learning design with I/Q
% DAC/ADC and real-time interfaces|. Under *Reference design parameters*,
% update the *DL Processor IP location* parameter value with the path of
% the generated deep learning HDL IP core. You can obtain this path from
% the IP core report. Update *DL Processor IP vendor* to |mathworks.com|.
%
% <<../IPCoreGenWorkflow2.png>>
%
% 3. In step 1.3, map the target platform interfaces to the input and
% output ports of the DUT.
%
% <<../AXIInterfaces.png>>
%
% *AXI4-Stream to Software Master Interface* &mdash;  The *Captured Data*
% and *Valid* ports of the DUT are mapped to the Data and Valid ports
% of the AXI4-Stream to Software Master interface, respectively.
% 
% *AXI4-Lite Interface* &mdash; The *DUTProcstart* register is mapped to
% the AXI4-Lite register. When this register is written, it triggers the
% input handshaking process. Choosing the AXI4-Lite interface directs HDL
% Coder(TM) to generate a memory-mapped register in the FPGA fabric. You
% can access this register from software by running on the ARM(R) processor.
% Other ports, such as *Trigger Capture*, *Stream Enable*, *txEnable*,
% *Ready*, and
% *Frame Size*, are also mapped to AXI4-Lite.
% 
% *AXI4 Master DL I/O Interface* &mdash; The *AXIWriteCtrlInDDR*,
% *AXIReadCtrlInDDR*, *AXIReadDataDDR*, *AXIWriteCtrlOutDDR*,
% *AXIWriteDataDDR*, and *AXIReadCtrlOutDDR* ports of the DUT are mapped to
% the AXI4 Master DDR interface. The read channel of the AXI4 Master DDR
% interface is mapped to the *Deep Learning I/O memory read interface*,
% and the write channel of the AXI4 Master DDR interface is mapped to the
% *Deep Learning I/O memory write interface*. This interface is used for
% data transfer between the |Preprocess| DUT and the PL DDR. Using the
% write channel of this interface, the preprocessed data is written to the
% PL DDR, which can then be accessed by the deep learning processor IP.
% 
% *AXI4 Master DL Interface* &mdash; The *AXIReadDataDL*,
% *AXIReadCtrlInDL*,
% *AXIWriteCtrlInDL*, *AXIReadCtrlOutDL*, *AXIWriteDataDL*, and
% *AXIWriteCtrlOutDL* ports of the DUT are mapped to the AXI4 Master deep
% learning interface. The read channel of the AXI4 Master deep learning
% interface is mapped to the *Deep Learning interface Read*, and the write
% channel of the AXI4 Master deep learning interface is mapped to the *Deep
% Learning interface write*. This interface is used for communication
% between the |Modulation Classification| DUT and the deep learning
% processor IP. In this example, this interface is used for implementing
% input handshaking logic with the deep learning processor IP.
% 
% 4. Run step 2 to prepare the design for HDL code generation.
%
% 5. Run step 3 to generate HDL code for the IP core.
%
% 6. Run step 4.1 to integrate the newly generated IP core into the
% reference design.
%
% 7. In step 4.2, the host interface script is created. Clear the *Generate
% Simulink software interface model* check box, as this example does not
% require software interface models. The host interface script,
% |soc_dlmc_rfsoc_interface|, which is generated in this step
% is parameterized and provided as the |setupPreprocessIPInterfaces|
% function as part of this example.
%
% <<../IPCoreGenWorkflow3.png>>
%
% 8. Run step 4.3 to generate the bitstream. The bit file is named
% |system_wrapper.bit| and is located at
% |hdl_prj\vivado_ip_prj\vivado_prj.runs\impl_1|. 
% 


